#!/usr/bin/env python3
"""Build a redacted public profile template from a real profile yaml.

Reads your real profile (default: profile/theo.yaml — gitignored, never
committed) and writes profile_template/example.yaml with identity, secrets,
drive IDs, compensation, and personal answers replaced by placeholders.

Two redaction layers:
  1. Key-based: known-personal subtrees and keys (user block, application
     answers, drive IDs, secrets, compensation) become placeholders.
  2. Identity sweep: your name / email / phone / LinkedIn are replaced
     wherever they appear in free-text fields (prompts, rationales, signals),
     including name variants like TheoKelly_CV.pdf filenames and outputs/theo
     paths.

Example lists are trimmed to a small representative set (target_companies:
one per ATS kind, up to 5; other long lists: first 5).

Verification is fail-closed. Secret fields are checked at their exact paths
in the output (so a public value like a Greenhouse board slug that also
appears in a website URL can't false-positive), and identity strings must
not appear anywhere. Any failure refuses to write.

Usage:
    python3 scripts/build_profile_template.py [SRC] [DST]

    Defaults: SRC=profile/theo.yaml DST=profile_template/example.yaml

Review DST before committing.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

HEADER = """\
# Example profile for job-application-agent.
# Generated by scripts/build_profile_template.py from a real profile, with
# identity, secrets, drive IDs, compensation, and personal answers redacted.
# Copy to profile/theo.yaml (the default profile path) and fill in your own.
"""

# Whole subtrees whose scalar values are personal.
REDACTED_SUBTREES = {"user", "application_answers", "differentiator",
                     "anchor_story", "work_authorization"}

# Lists replaced wholesale with a single TODO.
TODO_LIST_KEYS = {"supporting_stories", "credentials", "three_parts"}

# Key substrings marking secrets/identifiers at any depth.
SECRET_RES = [re.compile(p, re.I) for p in
              ("drive_id", "folder_id", "file_id", "token", "secret",
               "password", "api_key", "private_key")]

# ATS board identifiers are PUBLIC (they're interpolated into public job-board
# API URLs — Greenhouse boards-api, Lever postings API, Ashby posting-api, and
# Workday CXS all need no auth). Never redacted; they're useful examples.
PUBLIC_IDENTIFIERS = {"greenhouse_token", "lever_slug", "ashby_board",
                      "workday_board"}

# Example lists longer than this are trimmed to a representative set.
MAX_EXAMPLES = 5
ATS_KIND_KEYS = ("greenhouse_token", "lever_slug", "ashby_board", "workday_board")


def representative_companies(companies: list, limit: int = MAX_EXAMPLES) -> list:
    """Small representative set: one company per ATS kind, in priority order."""
    kept: list = []
    seen: set[str] = set()
    for c in companies:
        if not isinstance(c, dict):
            continue
        kind = next((k for k in ATS_KIND_KEYS if c.get(k)), "manual")
        if kind not in seen:
            seen.add(kind)
            kept.append(c)
        if len(kept) >= limit:
            break
    for c in companies:
        if len(kept) >= limit:
            break
        if all(c is not k for k in kept):
            kept.append(c)
    return kept


def trim_examples(node: object, key: str = "") -> object:
    """Trim long example lists to a small representative set."""
    if isinstance(node, list):
        if key == "target_companies":
            return [trim_examples(c, key) for c in representative_companies(node)]
        if len(node) > MAX_EXAMPLES:
            if all(isinstance(v, str) for v in node):
                return node[:MAX_EXAMPLES]
            if key in ("target_roles", "linkedin_search_queries"):
                return node[:MAX_EXAMPLES]
        return [trim_examples(v, key) for v in node]
    if isinstance(node, dict):
        return {k: trim_examples(v, k) for k, v in node.items()}
    return node

# Exact-key overrides, applied at any depth.
KEY_OVERRIDES = {
    "target_city": "Your City",
    "target_country": "Your Country",
    "relocation_status": "TODO",
    "target_base_eur": None,
    "target_total_eur": None,
    "notes": "TODO",
}

FIELD_PLACEHOLDERS = {
    "name": "Your Name",
    "email": "you@example.com",
    "phone": "+00 000 000 0000",
    "linkedin": "https://www.linkedin.com/in/your-handle",
    "current_location": "Your City, Country",
    "current_role": "Your Current Role",
    "current_role_end": "present",
    "employment_status": "employed",
}


def drive_or_secret(key: str) -> str:
    kl = key.lower()
    if "drive" in kl or "folder_id" in kl or "file_id" in kl:
        return "YOUR_GOOGLE_DRIVE_ID"
    return "YOUR_SECRET_HERE"


def redact_scalar(key: str, value: object) -> object:
    if isinstance(value, bool) or value is None:
        return value
    if not isinstance(value, str):
        return value  # numbers pass through (compensation handled via overrides)
    for rx in SECRET_RES:
        if rx.search(key):
            return drive_or_secret(key)
    return FIELD_PLACEHOLDERS.get(key, "TODO")


def redact(node: object, key: str = "", redacting: bool = False) -> object:
    if key in PUBLIC_IDENTIFIERS:
        return node
    if isinstance(node, dict):
        if key and any(rx.search(key) for rx in SECRET_RES):
            return "YOUR_SECRET_HERE"
        redacting = redacting or key in REDACTED_SUBTREES
        return {k: redact(v, k, redacting) for k, v in node.items()}
    if isinstance(node, list):
        if key in TODO_LIST_KEYS or redacting:
            return ["TODO"]
        return [redact(v, key, redacting) for v in node]
    if key in KEY_OVERRIDES:
        return KEY_OVERRIDES[key]
    if any(rx.search(key) for rx in SECRET_RES):
        return drive_or_secret(key)
    return redact_scalar(key, node) if redacting else node


def identity_pairs(src: dict) -> list[tuple[str, str]]:
    """(original, placeholder) for identity strings worth scrubbing.

    Includes name variants (full, concatenated, lowercase, first name) so
    filenames like TheoKelly_CV.pdf and paths like outputs/theo are caught.
    Sorted longest-first so replacements don't overlap.
    """
    user = src.get("user") or {}
    pairs: list[tuple[str, str]] = []
    name = user.get("name")
    if isinstance(name, str) and len(name) >= 4:
        nospace = name.replace(" ", "")
        pairs.append((name, "Your Name"))
        if nospace.lower() != name.lower():
            pairs.append((nospace, "yourname"))
        first = name.split()[0].lower()
        if len(first) >= 3 and first != nospace.lower():
            pairs.append((first, "yourname"))
    for k, ph in FIELD_PLACEHOLDERS.items():
        if k == "name":
            continue
        v = user.get(k)
        # Skip values already equal to the placeholder (nothing to scrub).
        if isinstance(v, str) and len(v) >= 4 and v != ph:
            pairs.append((v, ph))
    pairs.sort(key=lambda p: len(p[0]), reverse=True)
    return pairs


def scrub_identity(node: object, pairs: list[tuple[str, str]]) -> object:
    """Replace identity strings wherever they appear in free text."""
    if isinstance(node, dict):
        return {k: scrub_identity(v, pairs) for k, v in node.items()}
    if isinstance(node, list):
        return [scrub_identity(v, pairs) for v in node]
    if isinstance(node, str):
        lowered = node.lower()
        for orig, ph in pairs:
            if orig.lower() in lowered:
                node = re.sub(re.escape(orig), ph, node, flags=re.IGNORECASE)
                lowered = node.lower()
    return node


def collect_secret_paths(src: dict) -> list[tuple[str, str]]:
    """(dotted path, value) for string values under secret-ish keys."""
    found: list[tuple[str, str]] = []

    def walk(n: object, path: str) -> None:
        if isinstance(n, dict):
            for k, v in n.items():
                p = f"{path}.{k}" if path else str(k)
                if (str(k) not in PUBLIC_IDENTIFIERS
                        and any(rx.search(str(k)) for rx in SECRET_RES)
                        and isinstance(v, str) and v):
                    found.append((p, v))
                walk(v, p)
        elif isinstance(n, list):
            for i, v in enumerate(n):
                walk(v, f"{path}[{i}]")

    walk(src, "")
    return found


def get_path(node: object, path: str) -> object:
    cur = node
    for part in re.findall(r"[^\.\[\]]+|\[\d+\]", path):
        if part.startswith("["):
            cur = cur[int(part[1:-1])]  # type: ignore[index]
        else:
            cur = cur[part]  # type: ignore[index]
    return cur


def main() -> int:
    src_path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("profile/theo.yaml")
    dst_path = (Path(sys.argv[2]) if len(sys.argv) > 2
                else Path("profile_template/example.yaml"))
    if not src_path.exists():
        print(f"profile not found: {src_path}", file=sys.stderr)
        return 1
    src = yaml.safe_load(src_path.read_text())

    pairs = identity_pairs(src)
    template = scrub_identity(redact(trim_examples(src)), pairs)

    body = yaml.safe_dump(
        template, sort_keys=False, allow_unicode=True, default_flow_style=False)
    out = yaml.safe_load(body)
    out_text = HEADER + body

    problems: list[str] = []
    # Verify 1: every secret field was replaced at its exact path. (Path-based,
    # not substring: a public slug like a Greenhouse board token may also
    # appear in a website URL, which is fine.)
    for path, original in collect_secret_paths(src):
        try:
            if get_path(out, path) == original:
                problems.append(f"not redacted: {path}")
        except (KeyError, IndexError, TypeError):
            problems.append(f"missing in output: {path}")
    # Verify 2: identity strings appear nowhere in the body. (Checked against
    # the body, not the header: the header intentionally names profile/theo.yaml.)
    # Case-insensitive, matching the sweep.
    body_lower = body.lower()
    for orig, _ in pairs:
        if orig.lower() in body_lower:
            problems.append(f"identity string surviving: {orig!r}")
    if problems:
        print("REFUSED: redaction incomplete:", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1

    # Best-effort schema validation (needs the package importable).
    try:
        from job_agent.config import validate_profile
        validate_profile(out, str(dst_path))
        print("schema validation: ok")
    except ImportError:
        print("schema validation: skipped (job_agent not importable)")
    except Exception as e:  # noqa: BLE001
        print(f"schema validation FAILED: {e}", file=sys.stderr)
        return 1

    dst_path.parent.mkdir(parents=True, exist_ok=True)
    dst_path.write_text(out_text)
    print(f"wrote {dst_path} ({len(out_text)} chars), redaction verified")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
